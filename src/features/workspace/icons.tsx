import type { ReactNode } from "react";

// 편집기 크롬용 선 아이콘. 툴바 아이콘과 같은 1.8 굵기·둥근 끝.
type IconProps = { size?: number; className?: string };

function Icon({
  size = 16,
  className,
  children,
}: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.8"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      {children}
    </svg>
  );
}

